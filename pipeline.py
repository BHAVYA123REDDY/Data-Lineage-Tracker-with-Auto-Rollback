"""Pipeline simulation and data lineage tracking (Phase 3).

This module keeps the demo simple:
  * It builds a lineage chain for every data source:
        source -> ingest_<source> -> transform_<source> -> warehouse_<source>
  * It can simulate a pipeline run, which creates a new data version and
    either succeeds or fails (randomly, or forced for the demo).
"""

import random

import database
import rollback

# How often a simulated run fails by default (0.3 = 30% of runs).
DEFAULT_FAILURE_PROBABILITY = 0.3

# Processing steps used to build each source's lineage chain.
LINEAGE_STEPS = [
    ("ingest", "step", "Read raw data from the source"),
    ("transform", "step", "Clean and transform the data"),
]


def initialize_lineage(sources, db_path=None):
    """Create lineage nodes and edges for the given sources (idempotent)."""
    created = 0
    for source in sources:
        chain = [(source, "source", f"Raw data source: {source}")]
        for step, _kind, desc in LINEAGE_STEPS:
            chain.append((f"{step}_{source}", "step", desc))
        chain.append((f"warehouse_{source}", "output", f"Final table for {source}"))

        # Create any missing nodes
        node_ids = []
        for name, node_type, description in chain:
            existing = database.find_lineage_node(name, db_path=db_path)
            if existing:
                node_ids.append(existing["id"])
            else:
                node_ids.append(
                    database.add_lineage_node(name, node_type, description, db_path=db_path)
                )
                created += 1

        # Create the edges that join the chain (only if no edge exists yet)
        existing_edges = {
            (e["from_name"], e["to_name"]) for e in database.get_lineage_edges(db_path=db_path)
        }
        for i in range(len(chain) - 1):
            from_name, to_name = chain[i][0], chain[i + 1][0]
            if (from_name, to_name) not in existing_edges:
                database.add_lineage_edge(
                    node_ids[i], node_ids[i + 1], step_name=chain[i + 1][0], db_path=db_path
                )

    return created


def get_lineage_chains(db_path=None):
    """Return one ordered chain per data source, ready for the dashboard."""
    edges = database.get_lineage_edges(db_path=db_path)
    sources = database.get_source_names(db_path=db_path)

    chains = []
    for source in sources:
        # Follow the edges starting at this source
        chain = [source]
        current = source
        while True:
            nxt = next((e["to_name"] for e in edges if e["from_name"] == current), None)
            if nxt is None or nxt in chain:
                break
            chain.append(nxt)
            current = nxt
        chains.append({"source": source, "nodes": chain})
    return chains


def simulate_pipeline_run(
    source_name,
    force_failure=False,
    failure_probability=None,
    db_path=None,
    rng=None,
):
    """Simulate one pipeline run for a source.

    Steps:
      1. Create a new version for the source (representing the new data).
      2. Decide success or failure (randomly, or forced).
      3. Record the pipeline run and update the version status.
      4. On failure, automatically roll back to the last successful version.

    Returns a dictionary describing what happened, including the rollback
    details when a failure occurred.
    """
    rng = rng or random.Random()

    # Work out the next version number for this source
    versions = [
        v for v in database.get_versions(db_path=db_path) if v["source_name"] == source_name
    ]
    next_number = max([v["version_number"] for v in versions], default=0) + 1

    version_id = database.add_version(
        source_name,
        next_number,
        f"Auto-generated by simulated pipeline run",
        status="active",
        db_path=db_path,
    )

    probability = (
        DEFAULT_FAILURE_PROBABILITY if failure_probability is None else failure_probability
    )
    failed = force_failure or (rng.random() < probability)

    rollback_result = None

    if failed:
        database.update_version_status(version_id, "failed", db_path=db_path)
        message = "Simulated failure: data quality check did not pass"
        run_id = database.add_pipeline_run(
            f"{source_name}_pipeline", version_id, "failure", message, db_path=db_path
        )
        status = "failure"

        # Automatic rollback: restore the last good version.
        if rollback.AUTO_ROLLBACK_ENABLED:
            rollback_result = rollback.perform_rollback(
                source_name,
                failed_run_id=run_id,
                failed_version_id=version_id,
                reason="Automatic rollback after pipeline failure",
                db_path=db_path,
            )
    else:
        rows = rng.randint(100, 1000)
        message = f"Processed {rows} rows successfully"
        run_id = database.add_pipeline_run(
            f"{source_name}_pipeline", version_id, "success", message, db_path=db_path
        )
        status = "success"

    return {
        "run_id": run_id,
        "source_name": source_name,
        "version_id": version_id,
        "version_number": next_number,
        "status": status,
        "message": message,
        "rollback": rollback_result,
        "rolled_back": bool(rollback_result and rollback_result["status"] == "rolled_back"),
        "restored_version_id": (rollback_result or {}).get("restored_version_id"),
    }


def get_dashboard_stats(db_path=None):
    """Small summary used by the dashboard header cards."""
    versions = database.get_versions(db_path=db_path)
    runs = database.get_pipeline_runs(db_path=db_path)
    rollbacks = database.get_rollback_logs(db_path=db_path)

    return {
        "total_versions": len(versions),
        "active_versions": len([v for v in versions if v["status"] == "active"]),
        "failed_versions": len([v for v in versions if v["status"] == "failed"]),
        "rolled_back_versions": len([v for v in versions if v["status"] == "rolled_back"]),
        "total_runs": len(runs),
        "successful_runs": len([r for r in runs if r["status"] == "success"]),
        "failed_runs": len([r for r in runs if r["status"] == "failure"]),
        "total_rollbacks": len(rollbacks),
        "last_run": runs[0] if runs else None,
    }
